import turtle
t = turtle
t.tracer(0,0)
size = 10
#head
t.color('gray')
t.fillcolor('lightgray')
t.seth(0)
t.begin_fill()
t.circle(size)
t.end_fill()
t.pu()
t.left(90)
t.fd(size/3)
t.right(90)
t.pd()
t.color('black')
t.fillcolor('black')
t.begin_fill()
t.circle(size/1.8)
t.end_fill()

#body

t.color('gray')
t.fillcolor('lightgray')
t.pu()
t.right(90)
t.fd(3)
t.left(90)
t.fd(size/2)
t.pd()

t.begin_fill()
t.circle(size, 80)
t.right(80)
t.circle(-size/2, 60)
t.right(35)
t.circle(-size, 80)
t.left(90)
t.forward(size*2)

t.circle(-size/2, 180)
t.right(5)
t.forward(size/2.5)
t.circle(size/5, 180)
t.forward(size/2.5)
t.circle(-size/2, 180)
t.right(5)
t.fd(size*2)

t.left(80)
t.circle(-size, 80)
t.right(25)
t.circle(-size/2, 60)
t.right(90)
t.circle(size, 80)
t.end_fill()
t.fd(size/5)

t.pu()
t.seth(270)
t.fd(size/2)
t.right(90)
t.fd(size/4)
t.left(90)
t.pd()
t.fillcolor('black')
t.begin_fill()
for i in range(2):
    t.fd(size/1.3)
    t.left(90)
    t.fd(size*1.17)
    t.left(90)
t.end_fill()

t.update()
t.done()